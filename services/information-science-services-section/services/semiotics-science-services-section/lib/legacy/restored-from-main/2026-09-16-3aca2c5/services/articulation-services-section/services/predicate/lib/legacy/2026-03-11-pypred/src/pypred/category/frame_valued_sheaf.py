"""Frame-valued cellular sheaf on a simplicial complex (Čech-style parallel-pair convention).

In the per-fiber Curry investigation on the Belnap fiber, the L+ shadow sheaf
has powerset-frame stalks and restriction-with-clopen morphisms. This module
provides the minimal machinery needed to compute H^0 (global sections) and
H_0 of the cosheaf side.

Conventions (matching the corpus markdown):
- Stalk at a higher cell σ = stalk at the smallest vertex of σ's underlying chain.
- Sheaf restriction from a face V_y (with x < y) to edge E_{xy} = the lattice
  restriction F(V_y) → F(V_x) of the underlying poset.
- Cosheaf extension is the right adjoint of the corresponding sheaf restriction.

H^0 (global sections) is computed by enumeration: tuples (c_v ∈ F(v))_v
satisfying restriction-coherence at every edge.

H_0 of the cosheaf is computed by union-find over identifications:
for each edge e and each z ∈ F(e), identify ι_x(z) ~ ι_y(extension_y(z)).
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Hashable

from .frame import FrameMorphism, PowersetFrame
from .simplicial_complex import Simplex, SimplicialComplex


@dataclass(frozen=True)
class FrameValuedSheaf:
    """Cellular sheaf on a simplicial complex with PowersetFrame stalks at vertices.

    Stalks at higher cells follow the Čech parallel-pair convention: the stalk
    at a simplex equals the stalk at the chain's smallest vertex.

    `vertex_stalks`: dict from vertex (Simplex of dim 0) to PowersetFrame.
    `vertex_restrictions`: dict from (smaller_vertex, larger_vertex) to FrameMorphism
        F(larger_vertex) → F(smaller_vertex). The convention treats vertices as
        elements of the underlying poset; the morphism captures "restrict to the
        smaller vertex's clopen / cell-set".
    """

    complex: SimplicialComplex
    vertex_stalks: dict[Simplex, PowersetFrame]
    vertex_restrictions: dict[tuple[Simplex, Simplex], FrameMorphism]

    def stalk_at(self, simplex: Simplex) -> PowersetFrame:
        """Return the stalk at any cell, using the parallel-pair convention."""
        smallest_vertex = Simplex((simplex.vertices[0],))
        return self.vertex_stalks[smallest_vertex]

    def edge_restriction_from_left(self, edge: Simplex) -> FrameMorphism:
        """For edge e = (x < y), the restriction F(V_x) → F(e) is identity
        (stalks match by parallel-pair convention)."""
        v_x = Simplex((edge.vertices[0],))
        return _identity_morphism(self.vertex_stalks[v_x])

    def edge_restriction_from_right(self, edge: Simplex) -> FrameMorphism:
        """For edge e = (x < y), the restriction F(V_y) → F(e) is the lattice
        restriction F(V_y) → F(V_x)."""
        v_x = Simplex((edge.vertices[0],))
        v_y = Simplex((edge.vertices[1],))
        return self.vertex_restrictions[(v_x, v_y)]

    def global_sections(self) -> set[tuple[tuple[Simplex, frozenset[Hashable]], ...]]:
        """Compute H^0 by enumerating tuples of stalk-elements that satisfy
        restriction-coherence at every edge.

        Returns a set of tuples; each tuple is a global section, represented
        as ((vertex, stalk_value), ...) for each vertex in deterministic order.
        """
        vertices = self.complex.cells(0)
        edges = self.complex.cells(1)

        # Cartesian product of all stalks
        from itertools import product

        all_stalks = [self.vertex_stalks[v] for v in vertices]
        all_choices = product(*[list(s.elements()) for s in all_stalks])

        result: set[tuple[tuple[Simplex, frozenset[Hashable]], ...]] = set()
        for choice in all_choices:
            assignment = dict(zip(vertices, choice))
            if self._is_global_section(assignment, edges):
                result.add(tuple((v, assignment[v]) for v in vertices))
        return result

    def _is_global_section(
        self,
        assignment: dict[Simplex, frozenset[Hashable]],
        edges: list[Simplex],
    ) -> bool:
        for edge in edges:
            v_x = Simplex((edge.vertices[0],))
            v_y = Simplex((edge.vertices[1],))
            # Both restrictions evaluated at the assignment must agree at edge stalk
            left = self.edge_restriction_from_left(edge)(assignment[v_x])
            right = self.edge_restriction_from_right(edge)(assignment[v_y])
            if left != right:
                return False
        return True

    def cosheaf_h0(self) -> dict[frozenset[tuple[Simplex, frozenset[Hashable]]], int]:
        """Compute H_0 of the cosheaf side (Curry equivalent of sheaf H^0).

        The cosheaf has the same stalks; extensions are right adjoints of
        the sheaf restrictions. H_0 = colimit = identifications generated by
        `(v_x, z) ~ (v_y, extension_y(z))` for each edge and z in edge stalk.

        Returns a dict mapping equivalence-class (as frozenset of representatives)
        to its size (number of representatives in that class).
        """
        from .frame import FrameMorphism as _FM  # for type hints only

        vertices = self.complex.cells(0)
        edges = self.complex.cells(1)

        # All disjoint elements: (vertex, stalk_element) pairs
        elements: set[tuple[Simplex, frozenset[Hashable]]] = set()
        for v in vertices:
            for x in self.vertex_stalks[v].elements():
                elements.add((v, x))

        # Union-find structure
        parent: dict[tuple[Simplex, frozenset[Hashable]], tuple[Simplex, frozenset[Hashable]]] = {
            e: e for e in elements
        }

        def find(x: tuple[Simplex, frozenset[Hashable]]) -> tuple[Simplex, frozenset[Hashable]]:
            while parent[x] != x:
                parent[x] = parent[parent[x]]
                x = parent[x]
            return x

        def union(a: tuple[Simplex, frozenset[Hashable]], b: tuple[Simplex, frozenset[Hashable]]) -> None:
            ra, rb = find(a), find(b)
            if ra != rb:
                # Pick canonical (the one with lexicographically-smaller vertex tuple)
                if (ra[0].vertices, sorted(ra[1])) < (rb[0].vertices, sorted(rb[1])):
                    parent[rb] = ra
                else:
                    parent[ra] = rb

        # Apply identifications for each edge
        for edge in edges:
            v_x = Simplex((edge.vertices[0],))
            v_y = Simplex((edge.vertices[1],))
            # Edge stalk = stalk at smallest vertex (v_x)
            # Sheaf restriction F(V_y) → F(V_x) is the lattice restriction
            # Extension on the cosheaf side is its right adjoint
            sheaf_restriction = self.vertex_restrictions[(v_x, v_y)]
            extension_y = sheaf_restriction.right_adjoint()
            # For each z ∈ edge stalk = F(V_x): (v_x, z) ~ (v_y, extension_y(z))
            for z in self.vertex_stalks[v_x].elements():
                union((v_x, z), (v_y, extension_y(z)))

        # Compute equivalence classes
        classes: dict[tuple[Simplex, frozenset[Hashable]], set[tuple[Simplex, frozenset[Hashable]]]] = {}
        for e in elements:
            r = find(e)
            classes.setdefault(r, set()).add(e)

        return {frozenset(s): len(s) for s in classes.values()}


def _identity_morphism(frame: PowersetFrame) -> FrameMorphism:
    return FrameMorphism(source=frame, target=frame, mapping=lambda x: x)
