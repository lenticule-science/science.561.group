"""The dihedral D4 gauge of Belnap FOUR.

Executable shadow of ``RelMath.Positing.D4Gauge``.  The existing Klein-four
gauge gives the order-preserving/reversing symmetries generated by negation and
conflation.  Adjoining the order-swap involution ``sigma`` completes the full
eight-element dihedral symmetry of the bilattice square:

``D8 = K4 union K4.sigma``.
"""

from __future__ import annotations

from dataclasses import dataclass
from enum import StrEnum

from pymetrologic import BL, four
from pymetrologic.orderswap import swap

__all__ = [
    "D8",
    "D8_ELEMENTS",
    "D4AutFourWitness",
    "D4DihedralWitness",
    "d4_is_aut_four",
    "d4_is_dihedral",
    "d8_act",
    "d8_inv",
    "d8_mul",
    "d8_order",
    "in_k4",
    "in_swap_coset",
]

FOUR = four()
FOUR_CHARGES: tuple[BL[int], ...] = (FOUR.none, FOUR.true, FOUR.false, FOUR.conflict)


class D8(StrEnum):
    """The eight dihedral gauge symmetries of FOUR."""

    id = "id"
    neg = "neg"
    conf = "conf"
    negConf = "negConf"
    swap = "swap"
    negSwap = "negSwap"
    confSwap = "confSwap"
    negConfSwap = "negConfSwap"


D8_ELEMENTS: tuple[D8, ...] = (
    D8.id,
    D8.neg,
    D8.conf,
    D8.negConf,
    D8.swap,
    D8.negSwap,
    D8.confSwap,
    D8.negConfSwap,
)


@dataclass(frozen=True, slots=True)
class D4DihedralWitness:
    """Group/presentation facts identifying the action as dihedral D4."""

    order_eight: bool
    faithful: bool
    multiplication_realizes_composition: bool
    associative: bool
    identity: bool
    inverses: bool
    rotation_order_four: bool
    reflection_order_two: bool
    dihedral_relation: bool
    swap_neg_swap_is_conf: bool
    non_abelian: bool

    @property
    def holds(self) -> bool:
        """All checked dihedral facts hold."""
        return (
            self.order_eight
            and self.faithful
            and self.multiplication_realizes_composition
            and self.associative
            and self.identity
            and self.inverses
            and self.rotation_order_four
            and self.reflection_order_two
            and self.dihedral_relation
            and self.swap_neg_swap_is_conf
            and self.non_abelian
        )


@dataclass(frozen=True, slots=True)
class D4AutFourWitness:
    """Order-effect facts for ``Aut(FOUR; {<=k, <=t})``."""

    k4_coset_preserves_order_families: bool
    swap_coset_exchanges_orders: bool
    cosets_partition: bool
    k4_closed: bool
    coset_bit_is_hom: bool

    @property
    def holds(self) -> bool:
        """All checked automorphism-of-unordered-orders facts hold."""
        return (
            self.k4_coset_preserves_order_families
            and self.swap_coset_exchanges_orders
            and self.cosets_partition
            and self.k4_closed
            and self.coset_bit_is_hom
        )


def d8_act(element: D8, charge: BL[int]) -> BL[int]:
    """Act on a FOUR charge by a D8 gauge element."""
    match element:
        case D8.id:
            return charge
        case D8.neg:
            return FOUR.neg(charge)
        case D8.conf:
            return FOUR.conflate(charge)
        case D8.negConf:
            return FOUR.neg(FOUR.conflate(charge))
        case D8.swap:
            return swap(charge)
        case D8.negSwap:
            return FOUR.neg(swap(charge))
        case D8.confSwap:
            return FOUR.conflate(swap(charge))
        case D8.negConfSwap:
            return FOUR.neg(FOUR.conflate(swap(charge)))


def d8_mul(left: D8, right: D8) -> D8:
    """Group multiplication: the element acting as ``left after right``."""
    target = tuple(d8_act(left, d8_act(right, charge)) for charge in FOUR_CHARGES)
    for candidate in D8_ELEMENTS:
        if tuple(d8_act(candidate, charge) for charge in FOUR_CHARGES) == target:
            return candidate
    raise AssertionError("D8 actions are not closed under composition")


def d8_inv(element: D8) -> D8:
    """The inverse element under composition."""
    for candidate in D8_ELEMENTS:
        if d8_mul(candidate, element) is D8.id and d8_mul(element, candidate) is D8.id:
            return candidate
    raise AssertionError("D8 element has no inverse")


def d8_order(element: D8) -> int:
    """Return the multiplicative order of a D8 element."""
    acc = D8.id
    for order in range(1, 9):
        acc = d8_mul(element, acc)
        if acc is D8.id:
            return order
    raise AssertionError("D8 element order exceeds group size")


def in_k4(element: D8) -> bool:
    """Whether ``element`` lies in the Klein-four subgroup."""
    return element in {D8.id, D8.neg, D8.conf, D8.negConf}


def in_swap_coset(element: D8) -> bool:
    """Whether ``element`` lies in the order-swapping coset."""
    return not in_k4(element)


def d4_is_dihedral() -> D4DihedralWitness:
    """Bundle the executable dihedral presentation checks."""
    r = D8.negSwap
    s = D8.swap
    return D4DihedralWitness(
        order_eight=len(D8_ELEMENTS) == 8 and len(set(D8_ELEMENTS)) == 8,
        faithful=_faithful(),
        multiplication_realizes_composition=_multiplication_realizes_composition(),
        associative=all(
            d8_mul(d8_mul(g, h), k) is d8_mul(g, d8_mul(h, k))
            for g in D8_ELEMENTS
            for h in D8_ELEMENTS
            for k in D8_ELEMENTS
        ),
        identity=all(d8_mul(D8.id, g) is g and d8_mul(g, D8.id) is g for g in D8_ELEMENTS),
        inverses=all(
            d8_mul(d8_inv(g), g) is D8.id and d8_mul(g, d8_inv(g)) is D8.id for g in D8_ELEMENTS
        ),
        rotation_order_four=d8_order(r) == 4,
        reflection_order_two=d8_order(s) == 2,
        dihedral_relation=d8_mul(d8_mul(s, r), s) is d8_inv(r),
        swap_neg_swap_is_conf=d8_mul(d8_mul(D8.swap, D8.neg), D8.swap) is D8.conf,
        non_abelian=d8_mul(D8.neg, D8.swap) is not d8_mul(D8.swap, D8.neg),
    )


def d4_is_aut_four() -> D4AutFourWitness:
    """Bundle the order-family automorphism facts for FOUR."""
    return D4AutFourWitness(
        k4_coset_preserves_order_families=all(
            _k4_order_signature(g) for g in D8_ELEMENTS if in_k4(g)
        ),
        swap_coset_exchanges_orders=all(
            _swap_coset_order_signature(g) for g in D8_ELEMENTS if in_swap_coset(g)
        ),
        cosets_partition=all(in_k4(g) != in_swap_coset(g) for g in D8_ELEMENTS),
        k4_closed=all(
            in_k4(d8_mul(g, h)) for g in D8_ELEMENTS for h in D8_ELEMENTS if in_k4(g) and in_k4(h)
        ),
        coset_bit_is_hom=all(
            in_swap_coset(d8_mul(g, h)) == (in_swap_coset(g) != in_swap_coset(h))
            for g in D8_ELEMENTS
            for h in D8_ELEMENTS
        ),
    )


def _faithful() -> bool:
    actions = {
        element: tuple(d8_act(element, charge) for charge in FOUR_CHARGES)
        for element in D8_ELEMENTS
    }
    return len(set(actions.values())) == len(D8_ELEMENTS)


def _multiplication_realizes_composition() -> bool:
    return all(
        d8_act(d8_mul(g, h), charge) == d8_act(g, d8_act(h, charge))
        for g in D8_ELEMENTS
        for h in D8_ELEMENTS
        for charge in FOUR_CHARGES
    )


def _k4_order_signature(element: D8) -> bool:
    return all(
        _same_order_family(element, left, right) for left in FOUR_CHARGES for right in FOUR_CHARGES
    )


def _swap_coset_order_signature(element: D8) -> bool:
    return all(
        _swaps_order_family(element, left, right) for left in FOUR_CHARGES for right in FOUR_CHARGES
    )


def _same_order_family(element: D8, left: BL[int], right: BL[int]) -> bool:
    acted_left = d8_act(element, left)
    acted_right = d8_act(element, right)
    match element:
        case D8.id:
            return FOUR.leq_k(acted_left, acted_right) == FOUR.leq_k(left, right) and FOUR.leq_t(
                acted_left, acted_right
            ) == FOUR.leq_t(left, right)
        case D8.neg:
            return FOUR.leq_k(acted_left, acted_right) == FOUR.leq_k(left, right) and FOUR.leq_t(
                acted_left, acted_right
            ) == FOUR.leq_t(right, left)
        case D8.conf:
            return FOUR.leq_k(acted_left, acted_right) == FOUR.leq_k(right, left) and FOUR.leq_t(
                acted_left, acted_right
            ) == FOUR.leq_t(left, right)
        case D8.negConf:
            return FOUR.leq_k(acted_left, acted_right) == FOUR.leq_k(right, left) and FOUR.leq_t(
                acted_left, acted_right
            ) == FOUR.leq_t(right, left)
        case _:
            return False


def _swaps_order_family(element: D8, left: BL[int], right: BL[int]) -> bool:
    acted_left = d8_act(element, left)
    acted_right = d8_act(element, right)
    match element:
        case D8.swap:
            return FOUR.leq_k(acted_left, acted_right) == FOUR.leq_t(left, right) and FOUR.leq_t(
                acted_left, acted_right
            ) == FOUR.leq_k(left, right)
        case D8.negSwap:
            return FOUR.leq_k(acted_left, acted_right) == FOUR.leq_t(left, right) and FOUR.leq_t(
                acted_left, acted_right
            ) == FOUR.leq_k(right, left)
        case D8.confSwap:
            return FOUR.leq_k(acted_left, acted_right) == FOUR.leq_t(right, left) and FOUR.leq_t(
                acted_left, acted_right
            ) == FOUR.leq_k(left, right)
        case D8.negConfSwap:
            return FOUR.leq_k(acted_left, acted_right) == FOUR.leq_t(right, left) and FOUR.leq_t(
                acted_left, acted_right
            ) == FOUR.leq_k(right, left)
        case _:
            return False
