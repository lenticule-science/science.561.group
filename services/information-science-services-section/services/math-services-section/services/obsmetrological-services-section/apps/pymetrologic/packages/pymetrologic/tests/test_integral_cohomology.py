"""Integer-coefficient Hⁿ in arbitrary degree (extension beyond the Lean corpus).

Gold-standard checks against textbook simplicial cohomology groups, plus the
point of the whole exercise: ``hn_trivial_above_one`` asserts ``Hⁿ`` is a
point for ``n ≥ 2`` on Obsmetrologia's settling site by construction, but
that is a scope decision, not a theorem — a general simplicial complex can
have genuinely nonzero, even torsion, cohomology in degree ``≥ 2``. See
``pymetrologic.calculus.integral_cohomology``'s module docstring for the
full provenance story (ported/completed from pypredcalc; no Lean theorem
realized here).
"""

from __future__ import annotations

from itertools import combinations

from pymetrologic.calculus import IntegralCohomology, integral_cohomology
from pymetrologic.calculus.cohomology import hn_trivial_above_one
from pymetrologic.simplicial import Simplex, SimplicialComplex


def _closure(facets: list[tuple[int, ...]]) -> SimplicialComplex:
    """Build the simplicial complex generated by a list of top-dimensional facets."""
    simplices: set[Simplex] = set()
    for facet in facets:
        vertices = tuple(sorted(facet))
        for r in range(1, len(vertices) + 1):
            for combo in combinations(vertices, r):
                simplices.add(Simplex(combo))
    return SimplicialComplex(frozenset(simplices))


def _circle() -> SimplicialComplex:
    return _closure([(0, 1), (1, 2), (0, 2)])


def _sphere(dim: int) -> SimplicialComplex:
    """The boundary of the ``(dim + 1)``-simplex — a triangulated ``dim``-sphere."""
    return _closure(list(combinations(range(dim + 2), dim + 1)))


def _real_projective_plane() -> SimplicialComplex:
    """The standard minimal 6-vertex, 15-edge, 10-triangle triangulation of RP²."""
    facets = [
        (1, 2, 5),
        (1, 2, 6),
        (1, 3, 4),
        (1, 3, 6),
        (1, 4, 5),
        (2, 3, 4),
        (2, 3, 5),
        (2, 4, 6),
        (3, 5, 6),
        (4, 5, 6),
    ]
    return _closure(facets)


class TestCircle:
    """S¹: H⁰ = ℤ, H¹ = ℤ."""

    def test_h0_and_h1(self) -> None:
        sc = _circle()
        assert integral_cohomology(sc, 0) == IntegralCohomology(degree=0, betti=1, torsion=())
        assert integral_cohomology(sc, 1) == IntegralCohomology(degree=1, betti=1, torsion=())


class TestTwoSphere:
    """S², triangulated as the boundary of a 3-simplex (a tetrahedron): H⁰ = ℤ, H¹ = 0, H² = ℤ.

    This is the first witness that ``hn_trivial_above_one`` is a scope
    decision, not a theorem: a genuinely nonzero ``H²`` exists.
    """

    def test_betti_numbers(self) -> None:
        sc = _sphere(2)
        assert integral_cohomology(sc, 0) == IntegralCohomology(degree=0, betti=1, torsion=())
        assert integral_cohomology(sc, 1) == IntegralCohomology(degree=1, betti=0, torsion=())
        assert integral_cohomology(sc, 2) == IntegralCohomology(degree=2, betti=1, torsion=())

    def test_h2_is_nonzero_where_hn_trivial_above_one_would_claim_a_point(self) -> None:
        h2 = integral_cohomology(sc=_sphere(2), n=2)
        assert hn_trivial_above_one(2)  # the settling-site scope decision
        assert not h2.is_trivial()  # the actual computed group disagrees


class TestThreeSphere:
    """S³, triangulated as the boundary of a 4-simplex: H⁰ = ℤ, H³ = ℤ, everything else 0.

    A second, independent-degree witness (n = 3, not just n = 2) that
    higher-degree cohomology is not generally trivial.
    """

    def test_betti_numbers(self) -> None:
        sc = _sphere(3)
        for n in (1, 2):
            assert integral_cohomology(sc, n).is_trivial()
        assert integral_cohomology(sc, 0) == IntegralCohomology(degree=0, betti=1, torsion=())
        assert integral_cohomology(sc, 3) == IntegralCohomology(degree=3, betti=1, torsion=())

    def test_h3_is_nonzero_where_hn_trivial_above_one_would_claim_a_point(self) -> None:
        assert hn_trivial_above_one(3)
        assert not integral_cohomology(_sphere(3), 3).is_trivial()


class TestRealProjectivePlane:
    """RP²: the torsion case Smith Normal Form exists for.

    ``RP²`` has homology ``H₀ = ℤ``, ``H₁ = ℤ/2``, ``H₂ = 0``. By the
    universal coefficient theorem the *cohomology* torsion sits one degree
    higher than the matching homology torsion (``Hⁿ``'s torsion is
    ``H_{n-1}``'s torsion), so the ``ℤ/2`` surfaces here in ``H²``, not
    ``H¹`` — this test exists specifically to pin that degree shift down
    rather than assume the familiar "RP² has ℤ/2 in degree 1" homology fact
    transfers unchanged to cohomology.
    """

    def test_h0_is_z(self) -> None:
        assert integral_cohomology(_real_projective_plane(), 0) == IntegralCohomology(
            degree=0, betti=1, torsion=()
        )

    def test_h1_has_no_torsion(self) -> None:
        h1 = integral_cohomology(_real_projective_plane(), 1)
        assert h1.betti == 0
        assert h1.torsion == ()

    def test_h2_has_z2_torsion(self) -> None:
        h2 = integral_cohomology(_real_projective_plane(), 2)
        assert h2.betti == 0
        assert h2.torsion == (2,)
        assert not h2.is_trivial()


class TestBeyondComplexDimension:
    def test_cohomology_vanishes_above_the_complex_dimension(self) -> None:
        sc = _circle()  # a 1-dimensional complex
        assert integral_cohomology(sc, 5).is_trivial()
