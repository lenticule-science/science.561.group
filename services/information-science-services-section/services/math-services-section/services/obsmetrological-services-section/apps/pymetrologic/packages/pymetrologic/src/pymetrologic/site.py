"""The site — a finite predicate category as a poset of cells.

The base of a predication sheaf. In full generality this is the *predicate
category* ``C`` whose morphisms are generated by four classes (specialization,
converse, subject- and object-projection); a **cell complex / poset** is the
degenerate case where only specialization (restriction along a face inclusion)
survives. That degenerate case is exactly PySheaf's base, which is why a
cellular sheaf is the poset-only shadow of a predication sheaf.

A :class:`Site` is a finite set of cells with *face* relations ``a ◁ b``
("``a`` is a face of ``b``"); the partial order is the reflexive-transitive
closure. Restriction in a sheaf goes *along* a face, from the lower cell to its
coface.
"""

from __future__ import annotations

from collections.abc import Iterable
from dataclasses import dataclass

__all__ = ["Site"]

Cell = str
Face = tuple[Cell, Cell]


@dataclass(frozen=True)
class Site:
    """A finite poset of cells. ``faces`` are covering pairs ``(a, b)`` = ``a ◁ b``."""

    cells: tuple[Cell, ...]
    faces: tuple[Face, ...]

    def __post_init__(self) -> None:
        cellset = set(self.cells)
        if len(cellset) != len(self.cells):
            raise ValueError("duplicate cells")
        for a, b in self.faces:
            if a not in cellset or b not in cellset:
                raise ValueError(f"face {(a, b)} references an unknown cell")
            if a == b:
                raise ValueError(f"a cell cannot be its own face: {a}")
        if self._has_cycle():
            raise ValueError("face relation is cyclic; a site must be a poset")

    @classmethod
    def graph(cls, vertices: Iterable[str], edges: Iterable[tuple[str, str]]) -> Site:
        """Build the cell complex of an undirected graph.

        Vertices and edges are both cells; each edge ``{u, v}`` is a coface of
        its endpoints (``u ◁ uv``, ``v ◁ uv``). This is PySheaf's canonical
        "graph sheaf" shape: data on vertices, restricted onto shared edges.
        """
        verts = tuple(vertices)
        cells: list[Cell] = list(verts)
        faces: list[Face] = []
        for u, v in edges:
            e = cls.edge_name(u, v)
            cells.append(e)
            faces.append((u, e))
            faces.append((v, e))
        return cls(tuple(cells), tuple(faces))

    @staticmethod
    def edge_name(u: str, v: str) -> str:
        return f"{u}|{v}" if u <= v else f"{v}|{u}"

    def cofaces(self, cell: Cell) -> tuple[Cell, ...]:
        """Cells ``b`` with ``cell ◁ b`` (one step up)."""
        return tuple(b for a, b in self.faces if a == cell)

    def faces_of(self, cell: Cell) -> tuple[Cell, ...]:
        """Cells ``a`` with ``a ◁ cell`` (one step down)."""
        return tuple(a for a, b in self.faces if b == cell)

    def leq(self, a: Cell, b: Cell) -> bool:
        """Partial order ``a ≤ b`` (reflexive-transitive closure of ``◁``)."""
        if a == b:
            return True
        seen: set[Cell] = set()
        frontier = [a]
        while frontier:
            x = frontier.pop()
            for nb in self.cofaces(x):
                if nb == b:
                    return True
                if nb not in seen:
                    seen.add(nb)
                    frontier.append(nb)
        return False

    def _has_cycle(self) -> bool:
        colour: dict[Cell, int] = {}  # 0 = visiting, 1 = done

        def visit(node: Cell) -> bool:
            colour[node] = 0
            for nb in self.cofaces(node):
                c = colour.get(nb)
                if c == 0:
                    return True
                if c is None and visit(nb):
                    return True
            colour[node] = 1
            return False

        return any(colour.get(c) is None and visit(c) for c in self.cells)
