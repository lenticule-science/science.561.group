"""Transfinite cell complexes as colimits of finite subcomplexes.

Executable shadow of the cell-complex half of
``RelMath.Cohomology.TransfiniteCellComplex``.  The transfinite content is the
possibly large indexing of cells; each individual cell still has finite
dimension.  In the lab we carry a finite executable fragment: dimension drops
along face incidence, finite subcomplexes are downward-closed, unions make the
finite subcomplexes directed, and every cell lies in the generated finite
subcomplex of its faces.
"""

from __future__ import annotations

from collections.abc import Iterable, Mapping
from dataclasses import dataclass

type CellId = str
type FaceRelation = frozenset[tuple[CellId, CellId]]

__all__ = [
    "CellComplexColimitWitness",
    "FiniteSubcomplex",
    "TransfiniteCellComplex",
    "directed_finite_subcomplexes",
    "in_colimit_iff_some_finite",
    "transfinite_complex_is_colimit_of_finite",
]


@dataclass(frozen=True, slots=True)
class TransfiniteCellComplex:
    """A finite executable fragment of a transfinite cell complex."""

    cells: tuple[CellId, ...]
    dimensions: Mapping[CellId, int]
    faces: FaceRelation

    def __post_init__(self) -> None:
        if len(set(self.cells)) != len(self.cells):
            msg = "cell ids must be unique"
            raise ValueError(msg)
        cell_set = set(self.cells)
        if set(self.dimensions) != cell_set:
            msg = "dimensions must assign every cell exactly once"
            raise ValueError(msg)
        if any(dimension < 0 for dimension in self.dimensions.values()):
            msg = "cell dimensions must be natural numbers"
            raise ValueError(msg)
        if any(face not in cell_set or coface not in cell_set for face, coface in self.faces):
            msg = "face relation mentions an unknown cell"
            raise ValueError(msg)
        if any(self.dimensions[face] >= self.dimensions[coface] for face, coface in self.faces):
            msg = "face incidence must strictly drop dimension"
            raise ValueError(msg)

    def is_face(self, face: CellId, coface: CellId) -> bool:
        """Return whether ``face`` is an immediate face of ``coface``."""
        self._require_cell(face)
        self._require_cell(coface)
        return (face, coface) in self.faces

    def generated_subcomplex(self, cell: CellId) -> FiniteSubcomplex:
        """The finite downward closure generated by one cell."""
        self._require_cell(cell)
        closed = {cell}
        changed = True
        while changed:
            changed = False
            for face, coface in self.faces:
                if coface in closed and face not in closed:
                    closed.add(face)
                    changed = True
        return FiniteSubcomplex(self, frozenset(closed))

    def finite_subcomplex(self, cells: Iterable[CellId]) -> FiniteSubcomplex:
        """Construct a finite downward-closed subcomplex from explicit cells."""
        return FiniteSubcomplex(self, frozenset(cells))

    def _require_cell(self, cell: CellId) -> None:
        if cell not in self.cells:
            msg = f"unknown cell: {cell}"
            raise ValueError(msg)


@dataclass(frozen=True, slots=True)
class FiniteSubcomplex:
    """A finite subcomplex, represented by a downward-closed cell set."""

    complex: TransfiniteCellComplex
    cells: frozenset[CellId]

    def __post_init__(self) -> None:
        ambient = set(self.complex.cells)
        if not self.cells <= ambient:
            msg = "finite subcomplex contains an unknown cell"
            raise ValueError(msg)
        if not self.downward_closed:
            msg = "finite subcomplex must be downward-closed under faces"
            raise ValueError(msg)

    @property
    def downward_closed(self) -> bool:
        """Every face of an included cell is included."""
        return all(
            face in self.cells for face, coface in self.complex.faces if coface in self.cells
        )

    def contains(self, cell: CellId) -> bool:
        """Return whether this subcomplex contains ``cell``."""
        self.complex._require_cell(cell)
        return cell in self.cells

    def is_subcomplex_of(self, other: FiniteSubcomplex) -> bool:
        """Inclusion order on finite subcomplexes."""
        self._require_same_complex(other)
        return self.cells <= other.cells

    def union(self, other: FiniteSubcomplex) -> FiniteSubcomplex:
        """Directed-system upper bound: union of finite subcomplexes."""
        self._require_same_complex(other)
        return FiniteSubcomplex(self.complex, self.cells | other.cells)

    def _require_same_complex(self, other: FiniteSubcomplex) -> None:
        if self.complex != other.complex:
            msg = "finite subcomplexes must share the same ambient complex"
            raise ValueError(msg)


@dataclass(frozen=True, slots=True)
class CellComplexColimitWitness:
    """Bundled colimit facts for finite subcomplexes."""

    every_cell_in_generated_finite_subcomplex: bool
    finite_subcomplexes_directed: bool
    colimit_iff_some_finite: bool
    no_limit_cell_structure: bool

    @property
    def holds(self) -> bool:
        """All finite-colimit characterization checks hold."""
        return (
            self.every_cell_in_generated_finite_subcomplex
            and self.finite_subcomplexes_directed
            and self.colimit_iff_some_finite
            and self.no_limit_cell_structure
        )


def directed_finite_subcomplexes(left: FiniteSubcomplex, right: FiniteSubcomplex) -> bool:
    """Any two finite subcomplexes have a union upper bound."""
    union = left.union(right)
    return left.is_subcomplex_of(union) and right.is_subcomplex_of(union)


def in_colimit_iff_some_finite(complex: TransfiniteCellComplex, cell: CellId) -> bool:
    """A cell is in the colimit iff it lies in some finite subcomplex."""
    return complex.generated_subcomplex(cell).contains(cell)


def transfinite_complex_is_colimit_of_finite(
    complex: TransfiniteCellComplex,
) -> CellComplexColimitWitness:
    """Bundle the finite-subcomplex colimit characterization."""
    generated = tuple(complex.generated_subcomplex(cell) for cell in complex.cells)
    all_cells_recovered = frozenset().union(*(sub.cells for sub in generated)) == frozenset(
        complex.cells
    )
    directed = all(
        directed_finite_subcomplexes(left, right) for left in generated for right in generated
    )
    colimit = all(in_colimit_iff_some_finite(complex, cell) for cell in complex.cells)
    no_limit_cells = all(
        face in sub.cells
        for sub in generated
        for face, coface in complex.faces
        if coface in sub.cells
    )
    return CellComplexColimitWitness(
        every_cell_in_generated_finite_subcomplex=all_cells_recovered,
        finite_subcomplexes_directed=directed,
        colimit_iff_some_finite=colimit,
        no_limit_cell_structure=no_limit_cells,
    )
